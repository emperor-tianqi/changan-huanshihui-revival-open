def _parse_pairs(text: str) -> dict[int, int]:
    result: dict[int, int] = {}
    for pair in text.split(","):
        card_id, template_id = pair.split(":")
        result[int(card_id)] = int(template_id)
    return result


#: `card cfg id -> templeteId`.
CARD_TEMPLATE_IDS: dict[int, int] = _parse_pairs(",".join(_FROZEN_PAIRS))


def template_ids_digest(mapping: dict[int, int] | None = None) -> str:
    """sha256 over the canonical ``card:template`` pairs; the analyzer matches it."""

    table = CARD_TEMPLATE_IDS if mapping is None else mapping
    canonical = "|".join(f"{card}:{table[card]}" for card in sorted(table))
    return hashlib.sha256(canonical.encode("utf-8")).hexdigest()


TEMPLATE_DIGEST = template_ids_digest()


def template_id_for(card_cfg_id: int) -> int:
    """The handbook template id for one card config id.

    Refuses an unmapped id: the four client-only placeholder ids have no
    `templete` row, and inventing one would light a handbook entry the client's
    own `pkgCfgTempleteMgr` does not know.
    """

    try:
        return CARD_TEMPLATE_IDS[int(card_cfg_id)]
    except KeyError as exc:
        raise KeyError(
            f"card config id {card_cfg_id!r} has no shipped templete row"
        ) from exc
