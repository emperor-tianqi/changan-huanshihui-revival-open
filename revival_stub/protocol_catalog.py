_CATALOG_SPECS = {pid: ProtocolSpec(pid, name, fmt) for pid, name, fmt in KNOWN_C2S}


def catalog_spec(protocol_id: int) -> ProtocolSpec:
    """The client's own spec for one catalog id (read-only, no handler)."""

    return _CATALOG_SPECS[protocol_id]


class CatalogRegistry:
    """Decode with the implemented registry first, then the client catalog."""

    def __init__(self, implemented: ProtocolRegistry) -> None:
        self._implemented = implemented

    def by_id(self, protocol_id: int) -> ProtocolSpec:
        try:
            return self._implemented.by_id(protocol_id)
        except KeyError:
            return _CATALOG_SPECS[protocol_id]

    def by_name(self, name: str) -> ProtocolSpec:
        return self._implemented.by_name(name)

    def __len__(self) -> int:
        return len(_CATALOG_SPECS) + len(self._implemented)

    def __iter__(self):
        seen: set[int] = set()
        for spec in self._implemented:
            seen.add(spec.protocol_id)
            yield spec
        for pid, spec in _CATALOG_SPECS.items():
            if pid not in seen:
                yield spec

